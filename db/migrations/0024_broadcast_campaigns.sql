CREATE TABLE broadcast_campaigns (
  id VARBINARY(16) NOT NULL,
  admin_id VARBINARY(16) NOT NULL,
  admin_role VARCHAR(8) CHARACTER SET ascii COLLATE ascii_bin NOT NULL DEFAULT 'admin',
  client_campaign_id VARBINARY(16) NOT NULL,
  mfa_version INT UNSIGNED NOT NULL,
  payload_encrypted VARCHAR(32000) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  request_fingerprint VARBINARY(32) NOT NULL,
  media_id VARBINARY(16) NULL,
  allow_repeat_media TINYINT UNSIGNED NOT NULL DEFAULT 0,
  status VARCHAR(16) CHARACTER SET ascii COLLATE ascii_bin NOT NULL DEFAULT 'queued',
  created_at DATETIME(6) NOT NULL,
  updated_at DATETIME(6) NOT NULL,
  expires_at DATETIME(6) NOT NULL,
  PRIMARY KEY (id),
  UNIQUE KEY broadcast_campaigns_idempotency (admin_id, client_campaign_id),
  KEY broadcast_campaigns_owner_page (admin_id, id),
  KEY broadcast_campaigns_ready (status, created_at, id),
  KEY broadcast_campaigns_media (media_id),
  CONSTRAINT broadcast_campaigns_id_size CHECK (OCTET_LENGTH(id) = 16),
  CONSTRAINT broadcast_campaigns_admin_size CHECK (OCTET_LENGTH(admin_id) = 16),
  CONSTRAINT broadcast_campaigns_client_id_size CHECK (OCTET_LENGTH(client_campaign_id) = 16),
  CONSTRAINT broadcast_campaigns_fingerprint_size CHECK (OCTET_LENGTH(request_fingerprint) = 32),
  CONSTRAINT broadcast_campaigns_media_size CHECK (media_id IS NULL OR OCTET_LENGTH(media_id) = 16),
  CONSTRAINT broadcast_campaigns_admin_role CHECK (admin_role = 'admin'),
  CONSTRAINT broadcast_campaigns_mfa_version CHECK (mfa_version >= 1),
  CONSTRAINT broadcast_campaigns_payload CHECK (CHAR_LENGTH(payload_encrypted) BETWEEN 1 AND 32000),
  CONSTRAINT broadcast_campaigns_repeat CHECK (allow_repeat_media IN (0, 1)),
  CONSTRAINT broadcast_campaigns_status CHECK (status IN ('queued', 'running', 'completed', 'cancelled', 'paused')),
  CONSTRAINT broadcast_campaigns_dates CHECK (updated_at >= created_at AND expires_at > created_at AND expires_at <= created_at + INTERVAL 10080 MINUTE),
  CONSTRAINT broadcast_campaigns_owner_fk FOREIGN KEY (admin_id, admin_role)
    REFERENCES users (id, role) ON UPDATE RESTRICT ON DELETE RESTRICT,
  CONSTRAINT broadcast_campaigns_media_fk FOREIGN KEY (media_id)
    REFERENCES media_assets (id) ON UPDATE RESTRICT ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;

CREATE TABLE announcements (
  admin_id VARBINARY(16) NOT NULL,
  admin_role VARCHAR(8) CHARACTER SET ascii COLLATE ascii_bin NOT NULL DEFAULT 'admin',
  id VARBINARY(16) NOT NULL,
  revision BIGINT UNSIGNED NOT NULL,
  mutation_id VARBINARY(16) NOT NULL,
  request_fingerprint VARBINARY(32) NOT NULL,
  body_encrypted VARCHAR(8192) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  starts_at DATETIME(6) NOT NULL,
  expires_at DATETIME(6) NOT NULL,
  send_private_message TINYINT UNSIGNED NOT NULL,
  campaign_id VARBINARY(16) NULL,
  removed_at DATETIME(6) NULL,
  created_at DATETIME(6) NOT NULL,
  updated_at DATETIME(6) NOT NULL,
  PRIMARY KEY (admin_id),
  UNIQUE KEY announcements_id (id),
  KEY announcements_campaign (campaign_id),
  CONSTRAINT announcements_admin_size CHECK (OCTET_LENGTH(admin_id) = 16),
  CONSTRAINT announcements_id_size CHECK (OCTET_LENGTH(id) = 16),
  CONSTRAINT announcements_mutation_size CHECK (OCTET_LENGTH(mutation_id) = 16),
  CONSTRAINT announcements_fingerprint_size CHECK (OCTET_LENGTH(request_fingerprint) = 32),
  CONSTRAINT announcements_campaign_size CHECK (campaign_id IS NULL OR OCTET_LENGTH(campaign_id) = 16),
  CONSTRAINT announcements_admin_role CHECK (admin_role = 'admin'),
  CONSTRAINT announcements_revision CHECK (revision >= 1),
  CONSTRAINT announcements_payload CHECK (CHAR_LENGTH(body_encrypted) BETWEEN 1 AND 8192),
  CONSTRAINT announcements_send CHECK (send_private_message IN (0, 1)),
  CONSTRAINT announcements_window CHECK (expires_at > starts_at),
  CONSTRAINT announcements_lifetime CHECK (updated_at >= created_at),
  CONSTRAINT announcements_removed CHECK (removed_at IS NULL OR removed_at >= created_at),
  CONSTRAINT announcements_campaign_send CHECK (campaign_id IS NULL OR send_private_message = 1),
  CONSTRAINT announcements_owner_fk FOREIGN KEY (admin_id, admin_role)
    REFERENCES users (id, role) ON UPDATE RESTRICT ON DELETE RESTRICT,
  CONSTRAINT announcements_campaign_fk FOREIGN KEY (campaign_id)
    REFERENCES broadcast_campaigns (id) ON UPDATE RESTRICT ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
